def stage_oracle() -> dict[str, Any]:
    """Train-only residual corrections, evaluated on validation only.

    The train residual used for fitting is the *out-of-fold* residual from the
    Information Gap Audit (5-fold cross-fitted baseline protocol), so both
    the probe fit and its validation evaluation are out-of-sample.  The test
    split is never touched.
    """
    constants = _load_verified_constants()
    train = pd.read_csv(AUDIT_ROOT / "train_cycle_audit_label.csv")
    train["molecule_id"] = train["molecule_id"].astype(str)
    oof = _train_oof()
    train = train.merge(oof, on="molecule_id", how="inner")
    valid = pd.read_csv(AUDIT_ROOT / "valid_cycle_audit_label.csv")
    valid["molecule_id"] = valid["molecule_id"].astype(str)
    # cross-check against the info-gap audit table (both must come from the
    # same selection model); the cycle-audit table already carries pred/resid
    ig = _valid_predictions()
    assert len(valid) == len(ig), (len(valid), len(ig))
    assert np.allclose(valid["compact_v2_prediction"].to_numpy(),
                       ig["compact_v2_prediction"].to_numpy(), atol=1e-9), "pred mismatch"
    baseline_mae = float(valid["absolute_error"].mean())

    def evaluate(corr: np.ndarray, name: str, params: int) -> dict[str, Any]:
        corrected = valid["compact_v2_prediction"].to_numpy() + corr
        mae = float(mean_absolute_error(corrected, valid["target"].to_numpy()))
        return {
            "method": name,
            "params": params,
            "baseline_val_mae": baseline_mae,
            "corrected_val_mae": mae,
            "delta_mae": baseline_mae - mae,
            "verdict": (
                "very strong" if baseline_mae - mae >= 0.015 else
                "strong" if baseline_mae - mae >= 0.008 else
                "mild" if baseline_mae - mae >= 0.003 else "weak"
            ),
        }

    results: list[dict[str, Any]] = [{
        "method": "baseline (no correction)",
        "params": 0,
        "baseline_val_mae": baseline_mae,
        "corrected_val_mae": baseline_mae,
        "delta_mae": 0.0,
        "verdict": "-",
    }]

    def fit_predict_linear(feature_col: str, scale: bool = False) -> np.ndarray:
        xtrain = train[[feature_col]].to_numpy(dtype=float)
        xvalid = valid[[feature_col]].to_numpy(dtype=float)
        if scale:
            scaler = StandardScaler().fit(xtrain)
            xtrain = scaler.transform(xtrain)
            xvalid = scaler.transform(xvalid)
        target = train["signed_residual"].to_numpy()
        model = LinearRegression().fit(xtrain, target)
        return model.predict(xvalid)

    def fit_predict_binned(col: str, bin_edges: list[float]) -> np.ndarray:
        # binned medians of OOF train residual per excess bucket
        bins = np.array(bin_edges, dtype=float)
        assert np.all(np.diff(bins) > 0), "bin edges must be strictly increasing"
        cut = pd.cut(train[col], bins=bins, labels=[f"b{i}" for i in range(len(bins) - 1)])
        med = train.groupby(cut, observed=True)["signed_residual"].median()
        cutv = pd.cut(valid[col], bins=bins, labels=[f"b{i}" for i in range(len(bins) - 1)])
        return valid.assign(b=cutv).join(
            med.rename("med"), on="b")["med"].fillna(med.iloc[-1]).to_numpy()

    # 1) simple linear probe on final cycle component (2 params)
    corr = fit_predict_linear("final_cycle_component", scale=True)
    results.append(evaluate(corr, "linear probe: cycle component (train OOF fit)", 2))
    # linear probe restricted to the label-implied (refined) cycle component
    if (AUDIT_ROOT / "label_effective_cycle.csv").exists():
        lab = pd.read_csv(AUDIT_ROOT / "label_effective_cycle.csv")
        lab["molecule_id"] = lab["molecule_id"].astype(str)
        train_l = train.merge(lab[["molecule_id", "label_normalized_cycle_component"]],
                              on="molecule_id", how="left")
        valid_l = valid.merge(lab[["molecule_id", "label_normalized_cycle_component"]],
                              on="molecule_id", how="left")
        xtr = train_l[["label_normalized_cycle_component"]].to_numpy(dtype=float)
        xva = valid_l[["label_normalized_cycle_component"]].to_numpy(dtype=float)
        scaler = StandardScaler().fit(xtr)
        lr2 = LinearRegression().fit(scaler.transform(xtr), train_l["signed_residual"].to_numpy())
        corr_l = lr2.predict(scaler.transform(xva))
        results.append(evaluate(
            corr_l, "linear probe: label-implied cycle component (train OOF fit)", 2))

    # 2) linear probe on excess (2 params)
    corr = fit_predict_linear("excess_basis_cycle_length", scale=True)
    results.append(evaluate(corr, "linear probe: excess basis length (train OOF fit)", 2))

    # 3) binned median by excess (5 params)
    corr = fit_predict_binned("excess_basis_cycle_length",
                               [-0.5, 0.5, 1.5, 2.5, 3.5, 100.5])
    results.append(evaluate(corr, "binned-median probe: excess buckets (train OOF fit)", 5))

    # 4) monotonic isotonic on cycle score (train OOF fit)
    from sklearn.isotonic import IsotonicRegression

    iso = IsotonicRegression(out_of_bounds="clip").fit(
        train["final_cycle_component"].to_numpy(), train["signed_residual"].to_numpy()
    )
    corr = iso.predict(valid["final_cycle_component"].to_numpy())
    results.append(evaluate(corr, "isotonic probe: cycle component (train OOF fit)", 3))

    # 4b) invariant-statistic probes: permutation-invariant features only,
    #     i.e. the class of signal a (equivariant) model could ever see.
    def fit_predict_isotonic_col(col: str, increasing: bool = False) -> np.ndarray:
        iso = IsotonicRegression(out_of_bounds="clip", increasing=increasing).fit(
            train[col].to_numpy(dtype=float), train["signed_residual"].to_numpy()
        )
        return iso.predict(valid[col].to_numpy(dtype=float))

    for col, label in [
        ("longest_simple_cycle_length", "longest simple cycle (exact, invariant)"),
        ("max_min_basis_cycle_length", "max min-cycle-basis length (invariant)"),
        ("total_min_basis_cycle_length", "total min-cycle-basis length (invariant)"),
        ("rdkit_max_ring_size", "RDKit max ring size (invariant)"),
        ("mean_maxbasis", "mean max-basis over 10 random orders (invariant)"),
        ("frac_ge7", "frac random orders with max basis >= 7 (invariant)"),
    ]:
        corr = fit_predict_isotonic_col(col)
        results.append(
            evaluate(corr, f"isotonic probe: {label} (train OOF fit)", 3))

    # 4c) invariant linear-regression oracle: OOF 2-D polynomial surface on
    #     (longest simple cycle, min-basis total) - a richer invariant map.
    xtr = np.column_stack([
        train["longest_simple_cycle_length"].to_numpy(dtype=float),
        train["max_min_basis_cycle_length"].to_numpy(dtype=float),
        train["total_min_basis_cycle_length"].to_numpy(dtype=float),
    ])
    xva = np.column_stack([
        valid["longest_simple_cycle_length"].to_numpy(dtype=float),
        valid["max_min_basis_cycle_length"].to_numpy(dtype=float),
        valid["total_min_basis_cycle_length"].to_numpy(dtype=float),
    ])
    from sklearn.preprocessing import PolynomialFeatures

    poly = PolynomialFeatures(2, include_bias=False)
    Xtr = poly.fit_transform(xtr)
    Xva = poly.transform(xva)
    lr_poly = LinearRegression().fit(Xtr, train["signed_residual"].to_numpy())
    results.append(evaluate(
        lr_poly.predict(Xva),
        "poly-2 probe: 3 invariant cycle stats (train OOF fit)",
        Xtr.shape[1] + 1))

    # 4d) GradientBoosting probe on invariant stats - flexible upper bound
    #     of what an invariant cycle channel could express.
    from sklearn.ensemble import GradientBoostingRegressor
    gbr = GradientBoostingRegressor(
        n_estimators=120, max_depth=2, learning_rate=0.05, random_state=0)
    gbr.fit(xtr, train["signed_residual"].to_numpy())
    results.append(evaluate(
        gbr.predict(xva),
        "GBR probe: 3 invariant cycle stats (train OOF fit)",
        None))

    # 4e) GBR on randomized-basis invariant features (near-optimal invariant
    #     estimator of the order-dependent label cycle)
    xtr_r = np.column_stack([
        train["mean_maxbasis"].to_numpy(dtype=float),
        train["max_maxbasis"].to_numpy(dtype=float),
        train["min_maxbasis"].to_numpy(dtype=float),
        train["frac_ge7"].to_numpy(dtype=float),
        train["frac_ge9"].to_numpy(dtype=float),
    ])
    xva_r = np.column_stack([
        valid["mean_maxbasis"].to_numpy(dtype=float),
        valid["max_maxbasis"].to_numpy(dtype=float),
        valid["min_maxbasis"].to_numpy(dtype=float),
        valid["frac_ge7"].to_numpy(dtype=float),
        valid["frac_ge9"].to_numpy(dtype=float),
    ])
    gbr2 = GradientBoostingRegressor(
        n_estimators=150, max_depth=2, learning_rate=0.05, random_state=0)
    gbr2.fit(xtr_r, train["signed_residual"].to_numpy())
    results.append(evaluate(
        gbr2.predict(xva_r),
        "GBR probe: 5 randomized-basis invariant stats (train OOF fit)",
        None))
    # 3b) verified-cycle-component oracle: correct by the exact target term
    #     (TARGET-DEFINITION ORACLE - not a candidate predictive model).
    #     sign: r = y - y_hat ~= cycle_component (both negative), so the
    #     correction is r_hat = +cycle_component.
    corr = valid["verified_normalized_cycle_component"].to_numpy()
    corr = np.where(np.isnan(corr), 0.0, corr)
    oracle_row = evaluate(corr, "TARGET-DEFINITION ORACLE: subtract exact cycle term", 0)
    oracle_row["note"] = (
        "Uses knowledge of the benchmark target definition (exact normalized "
        "cycle component from the verified GVAE formula). NOT a candidate "
        "predictive model; cannot be compared with any actual method."
    )
    results.append(oracle_row)

    df = pd.DataFrame(results)
    df.to_csv(AUDIT_ROOT / "oracle_results.csv", index=False)
    return _mark_done("oracle", {
        "baseline_valid_mae": baseline_mae,
        "results": results,
        "table": str(AUDIT_ROOT / "oracle_results.csv"),
        "selection_policy": "all fits train-only (OOF residuals); valid transform+evaluate only; test untouched",
    })


