def _full_props_path() -> Path:
    return CACHE_DIR / "gvae_full_properties.npz"


def _compute_full_props(force: bool = False) -> dict[str, np.ndarray]:
    if _full_props_path().exists() and not force:
        return _load_npz(_full_props_path())
    smis = _load_smi_file()
    started = time.perf_counter()
    logp = np.full(len(smis), np.nan, dtype=np.float64)
    sa = np.full(len(smis), np.nan, dtype=np.float64)
    cyc = np.full(len(smis), np.nan, dtype=np.float64)
    with mp.Pool(N_PROCS) as pool:
        for line_idx, props in pool.imap_unordered(
            _worker_gvae_props, list(enumerate(smis)), chunksize=128
        ):
            if props is None:
                continue
            logp[line_idx] = props["logP"]
            sa[line_idx] = props["SA"]
            cyc[line_idx] = props["cycle"]
    _save_npz(_full_props_path(), logP=logp, SA=sa, cycle=cyc)
    return {"logP": logp, "SA": sa, "cycle": cyc}


def _dataset_stats(props: dict[str, np.ndarray]) -> dict[str, float]:
    valid = ~np.isnan(props["logP"])
    out = {}
    for key in ("logP", "SA", "cycle"):
        arr = props[key][valid]
        out[f"{key}_mean"] = float(arr.mean())
        out[f"{key}_std"] = float(arr.std())
    return out


def stage_verify() -> dict[str, Any]:
    props = _compute_full_props()
    logp, sa, cyc = props["logP"], props["SA"], props["cycle"]
    valid_mask = ~np.isnan(logp)
    dataset_stats = _dataset_stats(props)

    comparison = {}
    for name in ("logP_mean", "logP_std", "SA_mean", "SA_std", "cycle_mean", "cycle_std"):
        community = COMMUNITY_CONSTANTS[name]
        measured = dataset_stats[name]
        comparison[name] = {
            "community": community,
            "dataset": measured,
            "relative_diff": abs(measured - community) / max(abs(community), 1e-12),
        }

    cycle_values = sorted(set(cyc[valid_mask].tolist()))
    with gzip.open(_smi_index_path(), "rb") as handle:
        smi_index = pickle.load(handle)

    rows = []
    for split in ("train", "valid", "test"):
        data_list = _load_subset(split)
        for idx, data in enumerate(data_list):
            molecule_id = f"{split}:{idx:04d}"
            y_stored = float(data.y.reshape(-1)[0])
            cand_lines = _candidate_lines(smi_index, data)
            best_row = None
            for line in cand_lines:
                props_line = {"logP": float(logp[line]), "SA": float(sa[line]),
                              "cycle": float(cyc[line])}
                if np.isnan(props_line["logP"]):
                    continue
                y_recon_dataset = _gvae_normalized_target(props_line, dataset_stats)
                y_recon_community = _gvae_normalized_target(props_line, COMMUNITY_CONSTANTS)
                delta_ds = abs(y_recon_dataset - y_stored)
                if best_row is None or delta_ds < best_row["abs_delta_dataset"]:
                    best_row = {
                        "molecule_id": molecule_id,
                        "split": split,
                        "subset_index": idx,
                        "smi_line": line,
                        "logP": props_line["logP"],
                        "SA": props_line["SA"],
                        "cycle_score_gvae": props_line["cycle"],
                        "y_stored": y_stored,
                        "y_recon_dataset_stats": y_recon_dataset,
                        "abs_delta_dataset": delta_ds,
                        "y_recon_community_constants": y_recon_community,
                        "abs_delta_community": abs(y_recon_community - y_stored),
                        "n_candidates": len(cand_lines),
                        "matched": True,
                    }
            if best_row is None:
                best_row = {
                    "molecule_id": molecule_id, "split": split, "subset_index": idx,
                    "smi_line": -1, "matched": False,
                }
            rows.append(best_row)
    df = pd.DataFrame(rows)
    df.to_csv(AUDIT_ROOT / "formula_verification_per_molecule.csv", index=False)
    matched = df[df["matched"]]
    deltas = matched["abs_delta_dataset"] if len(matched) else pd.Series(dtype=float)
    return _mark_done("verify", {
        "n_full": int(valid_mask.sum()),
        "dataset_stats": dataset_stats,
        "community_comparison": comparison,
        "cycle_value_lattice": cycle_values,
        "n_subset": int(len(df)),
        "n_matched": int(len(matched)),
        "verified_exact_frac": float((deltas < 1e-4).mean()) if len(deltas) else 0.0,
        "delta_quantiles": {
            "p50": float(deltas.quantile(0.5)),
            "p95": float(deltas.quantile(0.95)),
            "max": float(deltas.max()),
        } if len(deltas) else {},
        "table": str(AUDIT_ROOT / "formula_verification_per_molecule.csv"),
    })


def _load_verified_constants() -> dict[str, float]:
    """Effective constants for the audit (dataset stats if verified, else
    community constants with an explicit flag on every output column)."""
    marker = _stage_marker("verify")
    default = dict(COMMUNITY_CONSTANTS)
    if marker.exists():
        payload = _read_json(marker)
        if payload.get("community_comparison") and payload.get("dataset_stats"):
            ds = payload["dataset_stats"]
            cc = payload["community_comparison"]
            all_close = all(
                cc[name]["relative_diff"] < 1e-6 for name in
                ("logP_mean", "logP_std", "SA_mean", "SA_std", "cycle_mean", "cycle_std")
            )
            if all_close:
                return {
                    "logP_mean": ds["logP_mean"], "logP_std": ds["logP_std"],
                    "SA_mean": ds["SA_mean"], "SA_std": ds["SA_std"],
                    "cycle_mean": ds["cycle_mean"], "cycle_std": ds["cycle_std"],
                }
    return default


def _verified_table() -> pd.DataFrame | None:
    path = AUDIT_ROOT / "formula_verification_per_molecule.csv"
