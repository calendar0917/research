def _worker_smi_cert(record: tuple[int, str]) -> tuple[int, str | None, int, int, bytes]:
    line_idx, smi = record
    mol = Chem.MolFromSmiles(smi)
    if mol is None:
        return line_idx, None, -1, -1, b""
    n_atoms = mol.GetNumAtoms()
    n_bonds = mol.GetNumBonds()
    graph = pynauty.Graph(n_atoms)
    for i in range(n_atoms):
        for j in range(i + 1, n_atoms):
            if mol.GetBondBetweenAtoms(i, j) is not None:
                graph.connect_vertex(i, j)
    cert = pynauty.certificate(graph)
    return line_idx, Chem.MolToSmiles(mol), n_atoms, n_bonds, cert


def _worker_gvae_props(record: tuple[int, str]) -> tuple[int, dict[str, float] | None]:
    line_idx, smi = record
    mol = Chem.MolFromSmiles(smi)
    if mol is None:
        return line_idx, None
    # GVAE pipeline: canonicalise first, then compute properties from the
    # canonical form (atom ordering follows the canonical SMILES).
    canonical = Chem.MolToSmiles(mol)
    mol2 = Chem.MolFromSmiles(canonical)
    return line_idx, _gvae_properties(mol2)


