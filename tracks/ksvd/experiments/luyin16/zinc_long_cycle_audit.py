def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "stages",
        nargs="*",
        choices=["provenance", "match", "verify", "refine", "audit", "perm", "oracle", "decision"],
        help="stages to run (default: all)",
    )
    parser.add_argument("--force", action="store_true", help="rebuild cached artifacts")
    args = parser.parse_args(argv)
    AUDIT_ROOT.mkdir(parents=True, exist_ok=True)
    stages = args.stages or ["provenance", "match", "verify", "refine", "audit",
                             "perm", "oracle", "decision"]
    runners = {
        "provenance": stage_provenance,
        "match": stage_match,
        "verify": stage_verify,
        "refine": stage_refine,
        "audit": stage_audit,
        "perm": stage_perm,
        "oracle": stage_oracle,
        "decision": stage_decision,
    }
    for stage in stages:
        if args.force or not _is_done(stage):
            started = time.perf_counter()
            print(f"[stage] {stage} ...", flush=True)
            result = runners[stage]()
            print(f"[done] {stage} in {time.perf_counter() - started:.1f}s", flush=True)
            print(json.dumps(result, ensure_ascii=False, indent=2)[:2500])
        else:
            print(f"[skip] {stage} already done (use --force)", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
