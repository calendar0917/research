def _cycle_basis_stats(graph: nx.Graph) -> dict[str, float]:
    """Candidate benchmark statistic: max length of ONE nx.cycle_basis.

    GVAE label formula: cycle_score = -max(0, max_basis_cycle_length - 6).
    NOT the graph's longest simple cycle (see note section 11).
    """
    if len(graph) == 0:
        cycles: list[list[int]] = []
    else:
        try:
            cycles = nx.cycle_basis(graph)
        except nx.NetworkXException:
            cycles = []
    max_len = max((len(c) for c in cycles), default=0)
    excess = max(max_len - 6, 0)
    return {
        "basis_cycle_count": float(len(cycles)),
        "max_basis_cycle_length": float(max_len),
        "excess_basis_cycle_length": float(excess),
        "cycle_score": float(-excess),
    }


def _min_cycle_basis_stats(graph: nx.Graph) -> dict[str, float]:
    if len(graph) == 0:
        return {
            "min_basis_cycle_count": 0.0,
            "max_min_basis_cycle_length": 0.0,
            "total_min_basis_cycle_length": 0.0,
        }
    basis = nx.minimum_cycle_basis(graph)
    lengths = [len(c) for c in basis]
    if not lengths:
        return {
            "min_basis_cycle_count": 0.0,
            "max_min_basis_cycle_length": 0.0,
            "total_min_basis_cycle_length": 0.0,
        }
    return {
        "min_basis_cycle_count": float(len(lengths)),
        "max_min_basis_cycle_length": float(max(lengths)),
        "total_min_basis_cycle_length": float(sum(lengths)),
    }


def _longest_simple_cycle(
    graph: nx.Graph, timeout_s: float = LONGEST_CYCLE_TIMEOUT_S
) -> dict[str, float]:
    """Exact longest simple cycle via oriented branch-and-bound DFS.

    status: 0 = exact, 1 = timed out (value is then a LOWER BOUND).
    Only used for extreme-tail molecules + samples (documented).  Exact
    longest simple cycle of an undirected graph is NP-hard in general.
    """
    materialized = graph.copy()
    materialized.remove_nodes_from([n for n in materialized if materialized.degree(n) == 0])
    if len(materialized) < 3:
        return {"longest_simple_cycle_length": 0.0, "longest_simple_cycle_status": 0.0}
    deadline = time.perf_counter() + timeout_s
    best = 2  # sentinel < 3

    def dfs(start: int, node: int, path: list[int], in_path: set[int]) -> None:
        nonlocal best
        if time.perf_counter() > deadline:
            return
        for nbr in materialized[node]:
            if nbr == start and len(path) >= 3:
                if len(path) > best:
                    best = len(path)
                continue
            if nbr in in_path:
                continue
            if nbr < start:
                continue  # orientation: cycles enumerated from their minimal vertex
            path.append(nbr)
            in_path.add(nbr)
            dfs(start, nbr, path, in_path)
            in_path.discard(nbr)
            path.pop()
            if time.perf_counter() > deadline:
                return

    for start_node in sorted(materialized.nodes):
        if time.perf_counter() > deadline:
            break
        dfs(start_node, start_node, [start_node], {start_node})

    timed_out = time.perf_counter() > deadline
    return {
        "longest_simple_cycle_length": float(best if best >= 3 else 0),
        "longest_simple_cycle_status": 1.0 if timed_out else 0.0,
    }


