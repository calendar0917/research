def _rdkit_ring_stats(mol: Chem.Mol | None) -> dict[str, float]:
    if mol is None:
        return {"rdkit_ring_count": np.nan, "rdkit_max_ring_size": np.nan,
                "rdkit_rings_gt_6": np.nan}
    rings = mol.GetRingInfo().AtomRings()
    sizes = [len(r) for r in rings]
    return {
        "rdkit_ring_count": float(len(sizes)),
        "rdkit_max_ring_size": float(max(sizes)) if sizes else 0.0,
        "rdkit_rings_gt_6": float(sum(1 for s in sizes if s > 6)),
    }


