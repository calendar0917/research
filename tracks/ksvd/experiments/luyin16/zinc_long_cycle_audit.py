_PERM_FLAT: list[tuple[str, int, Any]] = []


def _perm_init(flat: list[tuple[str, int, Any]]) -> None:
    global _PERM_FLAT
    _PERM_FLAT = flat


def _perm_shuffled_graph(graph: nx.Graph, seed: int, rng: np.random.Generator) -> nx.Graph:
    """Isomorphic copy whose *node insertion order* is the given permutation.

    nx.cycle_basis iterates nodes in insertion order; a relabelling alone
    (nx.relabel_nodes) preserves that order and therefore cannot test
    ordering sensitivity.  We rebuild the graph so the DFS/scan order is the
    permuted order (this is what happens when a user re-orders atoms and
    writes a fresh adjacency, e.g. when parsing a different SMILES order).
    """
    nodes = list(graph.nodes())
    order = rng.permutation(len(nodes))
    label_seq = [nodes[int(i)] for i in order]  # insertion order
    shuffled = nx.Graph()
    shuffled.add_nodes_from(label_seq)
    shuffled.add_edges_from(graph.edges())
    return shuffled


def _perm_worker(job: tuple[int, int]) -> tuple[int, int, float, float]:
    gi, k = job
    split, idx, data = _PERM_FLAT[gi]
    graph = _graph_from_data(data)
    rng = np.random.default_rng(gi * 1000003 + k * 7919 + 13)
    shuffled = _perm_shuffled_graph(graph, k, rng)
    cycles = nx.cycle_basis(shuffled)
    max_len = max((len(c) for c in cycles), default=0)
    return gi, k, float(max_len), float(len(cycles))


def _perm_minbasis_worker(job: tuple[int, int]) -> tuple[int, int, float]:
    gi, seed = job
    split, idx, data = _PERM_FLAT[gi]
    graph = _graph_from_data(data)
    rng = np.random.default_rng(seed)
    shuffled = _perm_shuffled_graph(graph, seed, rng)
    basis = nx.minimum_cycle_basis(shuffled)
    lengths = [len(c) for c in basis]
    return gi, seed, float(max(lengths) if lengths else 0)


def _perm_longest_worker(job: tuple[int, int]) -> tuple[int, int, float]:
    gi, seed = job
    split, idx, data = _PERM_FLAT[gi]
    graph = _graph_from_data(data)
    rng = np.random.default_rng(seed)
    shuffled = _perm_shuffled_graph(graph, seed, rng)
    return gi, seed, _longest_simple_cycle(shuffled, timeout_s=8.0)["longest_simple_cycle_length"]


