def _smi_index_path() -> Path:
    return CACHE_DIR / "smi_sidecars.pkl.gz"


def _build_smi_index(force: bool = False) -> dict[str, Any]:
    if _smi_index_path().exists() and not force:
        with gzip.open(_smi_index_path(), "rb") as handle:
            return pickle.load(handle)
    smis = _load_smi_file()
    started = time.perf_counter()
    with mp.Pool(N_PROCS) as pool:
        results = pool.map(_worker_smi_cert, list(enumerate(smis)), chunksize=256)
    index: dict[str, Any] = {"by_cert": {}, "canonical": {}, "parse_fail": [], "n": len(smis)}
    for line_idx, canonical, n_atoms, n_bonds, cert in results:
        if canonical is None:
            index["parse_fail"].append(line_idx)
            continue
        index["canonical"][line_idx] = canonical
        index["by_cert"].setdefault((n_atoms, n_bonds, cert), []).append(line_idx)
    with gzip.open(_smi_index_path(), "wb") as handle:
        pickle.dump(index, handle, protocol=pickle.HIGHEST_PROTOCOL)
    index["build_seconds"] = time.perf_counter() - started
    return index


def _cert_for_data(data: Any) -> bytes:
    graph = _graph_from_data(data)
    n_atoms = graph.number_of_nodes()
    pg = pynauty.Graph(n_atoms)
    for u, v in graph.edges():
        pg.connect_vertex(u, v)
    return pynauty.certificate(pg)


def _candidate_lines(smi_index: dict[str, Any], data: Any) -> list[int]:
    graph = _graph_from_data(data)
    n_atoms = graph.number_of_nodes()
    n_bonds = graph.number_of_edges()
    pg = pynauty.Graph(n_atoms)
    for u, v in graph.edges():
        pg.connect_vertex(u, v)
    cert = pynauty.certificate(pg)
    return smi_index["by_cert"].get((n_atoms, n_bonds, cert), [])


def stage_match() -> dict[str, Any]:
    index = _build_smi_index()
    match_rows = []
    n_candidates = 0
    n_zero = 0
    for split in ("train", "valid", "test"):
        data_list = _load_subset(split)
        for idx, data in enumerate(data_list):
            molecule_id = f"{split}:{idx:04d}"
            graph = _graph_from_data(data)
            n_atoms = graph.number_of_nodes()
            n_bonds = graph.number_of_edges()
            cert = _cert_for_data(data)
            hits = index["by_cert"].get((n_atoms, n_bonds, cert), [])
            match_rows.append({
                "molecule_id": molecule_id,
                "split": split,
                "subset_index": idx,
                "n_atoms": n_atoms,
                "n_bonds": n_bonds,
                "n_candidates": len(hits),
                "smi_lines": hits[:8],
            })
            n_candidates += len(hits)
            if len(hits) == 0:
                n_zero += 1
    pd.DataFrame(match_rows).to_csv(AUDIT_ROOT / "match_candidates.csv", index=False)
    mapping = {
        row["molecule_id"]: row["smi_lines"][0] if row["smi_lines"] else -1
        for row in match_rows
    }
    _write_json(
        CACHE_DIR / "subset_to_smi_lines.json",
        {"mapping": mapping, "candidate_table": str(AUDIT_ROOT / "match_candidates.csv")},
    )
    return _mark_done("match", {
        "n_subset": int(len(match_rows)),
        "n_candidates_total": int(n_candidates),
        "n_without_candidates": int(n_zero),
        "smi_parse_failures": len(index.get("parse_fail", [])),
        "smi_total": int(index["n"]),
        "candidate_table": str(AUDIT_ROOT / "match_candidates.csv"),
    })


