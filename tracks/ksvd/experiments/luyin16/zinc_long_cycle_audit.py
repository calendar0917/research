_SASCORER: Any = None


def _sascorer_module() -> Any:
    global _SASCORER
    if _SASCORER is None:
        path = UPSTREAM_DIR / "sascorer_gvae.py"
        spec = importlib.util.spec_from_file_location("sascorer_gvae", path)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        _SASCORER = module
    return _SASCORER


def _gvae_cycle_score(mol: Chem.Mol) -> int:
    """Verbatim semantics of generate_latent_features_and_targets.py."""
    adjacency = rdmolops.GetAdjacencyMatrix(mol)
    g = nx.from_numpy_array(adjacency)
    cycle_list = nx.cycle_basis(g)
    if len(cycle_list) == 0:
        cycle_length = 0
    else:
        cycle_length = max(len(j) for j in cycle_list)
    if cycle_length <= 6:
        cycle_length = 0
    else:
        cycle_length = cycle_length - 6
    return -cycle_length


def _gvae_properties(mol: Chem.Mol) -> dict[str, float]:
    sa = float(-_sascorer_module().calculateScore(mol))
    return {
        "logP": float(Descriptors.MolLogP(mol)),
        "SA": sa,
        "cycle": float(_gvae_cycle_score(mol)),
    }


def _gvae_normalized_target(props: Mapping[str, float], stats: Mapping[str, float]) -> float:
    return (
        (props["logP"] - stats["logP_mean"]) / stats["logP_std"]
        + (props["SA"] - stats["SA_mean"]) / stats["SA_std"]
        + (props["cycle"] - stats["cycle_mean"]) / stats["cycle_std"]
    )


