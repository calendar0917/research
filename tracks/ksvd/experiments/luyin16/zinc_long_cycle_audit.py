def _molecule_audit_rows(
    split: str,
    constants: Mapping[str, float],
    verified_table: pd.DataFrame | None,
    smi_index: dict[str, Any],
) -> list[dict[str, Any]]:
    data_list = _load_subset(split)
    rows = []
    vmap = (
        verified_table.set_index("molecule_id").to_dict("index")
        if verified_table is not None and "molecule_id" in verified_table
        else {}
    )
    for idx, data in enumerate(data_list):
        molecule_id = f"{split}:{idx:04d}"
        y = float(data.y.reshape(-1)[0])
        graph = _graph_from_data(data)
        bs = _cycle_basis_stats(graph)
        mb = _min_cycle_basis_stats(graph)
        cand_lines = _candidate_lines(smi_index, data)
        vrow = vmap.get(molecule_id, {})
        vline = int(vrow.get("smi_line", -1)) if vrow and vrow.get("matched") else -1
        # verified cycle component (GVAE canonical order) from the verify table
        if vline >= 0:
            cycle_score_verified = float(vrow.get("cycle_score_gvae", np.nan))
        else:
            cycle_score_verified = np.nan
        cand_cycle_score = bs["cycle_score"]  # stored node order
        def norm_cycle(score: float) -> float:
            return (score - constants["cycle_mean"]) / constants["cycle_std"]
        cand_comp = norm_cycle(cand_cycle_score) if not np.isnan(cand_cycle_score) else np.nan
        ver_comp = norm_cycle(cycle_score_verified) if not np.isnan(cycle_score_verified) else np.nan
        final_comp = ver_comp if not np.isnan(ver_comp) else cand_comp
        # longest simple cycle: only for the extreme-tail flag + sample handled
        # fully in the perm stage; here bounded cheap pass.
        lsc = (
            _longest_simple_cycle(graph, timeout_s=LONGEST_CYCLE_TIMEOUT_S)
            if y < -4
            else {"longest_simple_cycle_length": np.nan,
                  "longest_simple_cycle_status": -1.0}
        )
        mol = None
        if vline >= 0:
            canon = smi_index["canonical"].get(vline)
            mol = Chem.MolFromSmiles(canon) if canon else None
        ring = _rdkit_ring_stats(mol)
        row = {
            "molecule_id": molecule_id,
            "split": split,
            "subset_index": idx,
            "target": y,
            "n_nodes": float(graph.number_of_nodes()),
            "n_edges": float(graph.number_of_edges()),
            "basis_cycle_count": bs["basis_cycle_count"],
            "max_basis_cycle_length": bs["max_basis_cycle_length"],
            "excess_basis_cycle_length": bs["excess_basis_cycle_length"],
            "cycle_score_stored_order": cand_cycle_score,
            "candidate_normalized_cycle_component": cand_comp,
            "matched": bool(vline >= 0),
            "smi_line": vline,
            "cycle_score_gvae_order": cycle_score_verified,
            "verified_normalized_cycle_component": ver_comp,
            "final_cycle_component": final_comp,
            "y_without_cycle": y - final_comp if not np.isnan(final_comp) else np.nan,
            "min_basis_cycle_count": mb["min_basis_cycle_count"],
            "max_min_basis_cycle_length": mb["max_min_basis_cycle_length"],
            "total_min_basis_cycle_length": mb["total_min_basis_cycle_length"],
            "longest_simple_cycle_length": lsc["longest_simple_cycle_length"],
            "longest_simple_cycle_status": lsc["longest_simple_cycle_status"],
            "rdkit_ring_count": ring["rdkit_ring_count"],
            "rdkit_max_ring_size": ring["rdkit_max_ring_size"],
            "rdkit_rings_gt_6": ring["rdkit_rings_gt_6"],
        }
        rows.append(row)
    return rows


def _distribution_stats(arr: np.ndarray) -> dict[str, float]:
    arr = np.asarray(arr, dtype=np.float64)
    arr = arr[~np.isnan(arr)]
    if arr.size == 0:
        return {"n": 0.0, "min": np.nan, "q1": np.nan, "q5": np.nan,
                "median": np.nan, "max": np.nan, "std": np.nan,
                "skewness": np.nan, "kurtosis": np.nan, "mean": np.nan}
    return {
        "n": float(arr.size),
        "min": float(arr.min()),
        "q1": float(np.quantile(arr, 0.01)),
        "q5": float(np.quantile(arr, 0.05)),
        "median": float(np.median(arr)),
        "max": float(arr.max()),
        "std": float(arr.std()),
        "skewness": float(scipy_stats.skew(arr)),
        "kurtosis": float(scipy_stats.kurtosis(arr)),
        "mean": float(arr.mean()),
    }


def _corr_table(rows: pd.DataFrame) -> pd.DataFrame:
    out = []
    stats_list = [
        ("max_basis_cycle_length", "max basis-cycle length"),
        ("excess_basis_cycle_length", "excess basis-cycle length"),
        ("cycle_score_stored_order", "cycle score (stored order)"),
        ("candidate_normalized_cycle_component", "candidate normalized cycle component"),
        ("verified_normalized_cycle_component", "verified normalized cycle component"),
        ("final_cycle_component", "final cycle component"),
        ("max_min_basis_cycle_length", "max min-cycle-basis length"),
        ("total_min_basis_cycle_length", "total min-cycle-basis length"),
        ("longest_simple_cycle_length", "longest simple cycle"),
        ("rdkit_max_ring_size", "RDKit max ring size"),
        ("rdkit_rings_gt_6", "RDKit rings > 6"),
    ]
    for split, sub in rows.groupby("split"):
        for tail_name, mask in (
            ("all", pd.Series(True, index=sub.index)),
            ("y<-4", sub["target"] < -4),
            ("y<-6", sub["target"] < -6),
            ("y<-10", sub["target"] < -10),
        ):
            sub2 = sub[mask]
            if len(sub2) < 10:
                continue
            for col, label in stats_list:
                a = sub2[col].astype(float)
                b = sub2["target"].astype(float)
                ok = ~np.isnan(a) & ~np.isnan(b)
                if ok.sum() < 10 or a[ok].nunique() < 2:
                    continue
                out.append({
                    "split": split,
                    "subset": tail_name,
                    "n": int(ok.sum()),
                    "statistic": label,
                    "column": col,
                    "pearson_y": float(scipy_stats.pearsonr(b[ok], a[ok])[0]),
                    "spearman_y": float(scipy_stats.spearmanr(b[ok], a[ok])[0]),
                })
    return pd.DataFrame(out)


