def stage_refine() -> dict[str, Any]:
    """Reverse-engineer the label's cycle term per molecule.

    For each molecule with a verified identity: y_stored - [(logP-muL)/sL +
    (SA-muS)/sS] = (cycle - muC)/sC.  With the constants fitted on the
    cycle-free bulk (cycle_score_gvae == 0, robust), the implied cycle term
    snaps to the 0,-1,-2,... lattice with p95 error ~1e-3.  This gives the
    per-molecule cycle value the label generator actually used, independent
    of any assumed node ordering of our own.
    """
    df = pd.read_csv(AUDIT_ROOT / "formula_verification_per_molecule.csv")
    df["molecule_id"] = df["molecule_id"].astype(str)
    m = df[df["matched"]].copy()
    z0 = m[m["cycle_score_gvae"] == 0].copy()
    # robust fit on the cycle-free bulk
    X = z0[["logP", "SA"]].to_numpy()
    y = z0["y_stored"].to_numpy()
    lr = LinearRegression().fit(X, y)
    sL, sS = 1.0 / lr.coef_[0], 1.0 / lr.coef_[1]
    muL = COMMUNITY_CONSTANTS["logP_mean"]  # verified to ~3e-5 elsewhere
    muS = -sS * (lr.intercept_ + muL / sL)
    m["y_chem"] = (m["logP"] - muL) / sL + (m["SA"] - muS) / sS
    m["effective_cycle_norm"] = m["y_stored"] - m["y_chem"]

    from scipy.optimize import minimize

    def snap_loss(params: np.ndarray) -> float:
        sC, muC = float(params[0]), float(params[1])
        eff = m["effective_cycle_norm"].to_numpy() * sC + muC
        snap = np.clip(np.round(eff), -20, 0)
        return float(np.nanmean((eff - snap) ** 2))

    best = minimize(snap_loss, np.array([0.288, -0.049]), method="Nelder-Mead")
    sC, muC = float(best.x[0]), float(best.x[1])
    m["effective_cycle"] = m["effective_cycle_norm"] * sC + muC
    m["label_effective_cycle_snapped"] = np.clip(np.round(m["effective_cycle"]), -20, 0)
    m["snap_error"] = (m["effective_cycle"] - m["label_effective_cycle_snapped"]).abs()
    m["mismatch_vs_gvae_order"] = (
        (m["cycle_score_gvae"] - m["label_effective_cycle_snapped"]).abs() > 0
    )

    out_cols = [
        "molecule_id", "split", "subset_index", "y_stored", "logP", "SA",
        "effective_cycle_norm", "effective_cycle", "label_effective_cycle_snapped",
        "snap_error", "cycle_score_gvae", "mismatch_vs_gvae_order",
    ]
    out = m[out_cols].copy()
    out["label_normalized_cycle_component"] = (
        out["label_effective_cycle_snapped"] - muC
    ) / sC
    out.to_csv(AUDIT_ROOT / "label_effective_cycle.csv", index=False)

    summary = {
        "constants_fitted": {
            "sigma_logP": sL, "sigma_SA": sS, "mu_SA": muS,
            "sigma_cycle": sC, "mu_cycle": muC,
        },
        "snap_error": {
            "p50": float(m["snap_error"].median()),
            "p95": float(m["snap_error"].quantile(0.95)),
            "max": float(m["snap_error"].max()),
        },
        "n_total": int(len(m)),
        "n_agree": int((~m["mismatch_vs_gvae_order"]).sum()),
        "n_mismatch": int(m["mismatch_vs_gvae_order"].sum()),
        "mismatch_ids": m.loc[m["mismatch_vs_gvae_order"],
                              ["molecule_id", "y_stored", "cycle_score_gvae",
                               "label_effective_cycle_snapped", "snap_error"]].to_dict("records"),
    }
    return _mark_done("refine", summary)

