def _f(x: float | None, nd: int = 4) -> str:
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "n/a"
    return f"{x:.{nd}f}"


def stage_decision() -> dict[str, Any]:
    valid = _read_csv(str(AUDIT_ROOT / "valid_cycle_audit.csv"))
    all_df = pd.concat([
        _read_csv(str(AUDIT_ROOT / f"{s}_cycle_audit.csv")) for s in ("train", "valid", "test")
    ], ignore_index=True)
    corr = _read_csv(str(AUDIT_ROOT / "cycle_target_correlations.csv"))
    comp = _read_csv(str(AUDIT_ROOT / "split_cycle_composition.csv"))
    oracle = _read_csv(str(AUDIT_ROOT / "oracle_results.csv"))
    perm = _read_csv(str(AUDIT_ROOT / "permutation_sensitivity.csv"))
    dist = _read_csv(str(AUDIT_ROOT / "cycle_removed_distribution.csv"))
    shrink = _read_csv(str(AUDIT_ROOT / "shrinkage_groups.csv"))
    resid_b = _read_csv(str(AUDIT_ROOT / "valid_residual_by_excess.csv"))
    verify = _read_json(str(_stage_marker("verify")))
    provenance = _read_json(str(_stage_marker("provenance")))

    # --- decision signals -------------------------------------------------
    extreme = all_df[all_df["target"] < -4]
    n_extreme = int(len(extreme))
    extreme_with_cycle = int((extreme["excess_basis_cycle_length"] >= 1).sum())
    extreme_frac_with_cycle = extreme_with_cycle / max(n_extreme, 1)

    deep_tail = all_df[all_df["target"] < -10]
    deep_with_cycle = int((deep_tail["excess_basis_cycle_length"] >= 1).sum())

    # cycle-removed tail recovery
    dist_rows = dist[dist["quantity"].astype(str).str.startswith("count_y<")]
    removed_tail = {}
    for _, row in dist_rows.iterrows():
        removed_tail[f"{row['split']}_count_y{row['quantity'].split('<')[1]}_orig"] = int(
            row["n_original"]
        )
        removed_tail[f"{row['split']}_count_y{row['quantity'].split('<')[1]}_removed"] = int(
            row["n_without_cycle"]
        )

    # residual concentration
    resid_concentration = resid_b.to_dict("records")
    extreme_group_mae = resid_b.loc[resid_b["excess_group"].isin(
        ["excess=3", "excess>=4"]), "MAE"].max() if len(resid_b) else np.nan
    base_group_mae = resid_b.loc[resid_b["excess_group"] == "excess=0", "MAE"].min() \
        if len(resid_b) and (resid_b["excess_group"] == "excess=0").any() else np.nan

    # oracle verdict
    oracle_rows = oracle.to_dict("records")
    oracle_best = max(
        (r for r in oracle_rows if "TARGET" not in r["method"]),
        key=lambda r: r["delta_mae"],
    )

    # permutation instability
    n_tested = int(len(perm))
    n_unstable = int((perm["num_unique_basis_lengths"] > 1).sum())
    extreme_unstable = int(
        (perm[perm["is_extreme"]]["num_unique_basis_lengths"] > 1).sum()
    )
    n_extreme_tested = int(perm["is_extreme"].sum())

    # invariant-vs-basis comparison
    inv_corr = corr[(corr["subset"] == "all") & (corr["statistic"].isin([
        "longest simple cycle", "max min-cycle-basis length",
    ]))].to_dict("records")
    basis_corr = corr[(corr["subset"] == "all") & (corr["statistic"].isin([
        "max basis-cycle length", "verified normalized cycle component",
    ]))].to_dict("records")

    decision: dict[str, Any] = {
        "extreme_tail": {
            "n_y_lt_m4": n_extreme,
            "frac_with_long_cycle": extreme_frac_with_cycle,
            "n_y_lt_m10": int(len(deep_tail)),
            "deep_tail_frac_with_long_cycle": deep_with_cycle / max(len(deep_tail), 1),
        },
        "cycle_removed_tail": removed_tail,
        "residual_by_excess": resid_concentration,
        "residual_excess0_mae": float(base_group_mae) if not np.isnan(base_group_mae) else None,
        "residual_extreme_mae": float(extreme_group_mae) if not np.isnan(extreme_group_mae) else None,
        "oracle": oracle_rows,
        "best_predictive_oracle": oracle_best,
        "permutation": {
            "n_tested": n_tested,
            "n_unstable_total": n_unstable,
            "n_extreme_tested": n_extreme_tested,
            "n_extreme_unstable": extreme_unstable,
        },
        "correlations_invariant_vs_basis": {
            "invariant": inv_corr,
            "basis": basis_corr,
        },
        "verification": {
            "verified_exact_frac": verify.get("verified_exact_frac"),
            "delta_quantiles": verify.get("delta_quantiles"),
            "dataset_stats": verify.get("dataset_stats"),
            "community_comparison": verify.get("community_comparison"),
        },
        "split_composition": comp.to_dict("records"),
        "shrinkage_groups": shrink.to_dict("records"),
    }

    # --- decision rule (section 32) --------------------------------------
    oracle_delta = float(oracle_best["delta_mae"])
    rule_basis = (
        extreme_frac_with_cycle >= 0.8
        and (resid_excess0_mae * 3 < extreme_group_mae if resid_excess0_mae else False)
    )
    artifact_evidence = n_extreme_tested > 0 and extreme_unstable / max(n_extreme_tested, 1) >= 0.3

    if not rule_basis and oracle_delta < 0.003:
        rule = "NO-GO (mechanism not supported; back to tail-aware regression)"
    elif oracle_delta < 0.008:
        rule = "weak/mild signal - mechanism partially supported; revisit after benchmark-artifact check"
    elif artifact_evidence:
        rule = "GO - BENCHMARK ARTIFACT INVESTIGATION"
    else:
        rule = "GO - GLOBAL TOPOLOGY"

    decision["decision_rule_result"] = rule
    decision["rule_components"] = {
        "extreme_frac_with_cycle": extreme_frac_with_cycle,
        "residual_excess0_mae": float(base_group_mae) if not np.isnan(base_group_mae) else None,
        "residual_extreme_mae": float(extreme_group_mae) if not np.isnan(extreme_group_mae) else None,
        "oracle_delta_best_predictive": oracle_delta,
        "artifact_evidence_frac": extreme_unstable / max(n_extreme_tested, 1),
    }

    _write_json(AUDIT_ROOT / "decision_record.json", decision)
    return _mark_done("decision", {
        "decision": rule,
        "extreme_tail": decision["extreme_tail"],
        "oracle_delta_best_predictive": oracle_delta,
        "artifact_evidence": decision["rule_components"],
        "record": str(AUDIT_ROOT / "decision_record.json"),
    })


