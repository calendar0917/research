def test_parameter_counts(spec, norm):
    c1 = M.build_model(spec, norm, "c1")
    assert sum(p.numel() for p in c1.parameters() if p.requires_grad) == 228674
    wide = M.build_model(spec, norm, "wide_local")
    assert sum(p.numel() for p in wide.parameters() if p.requires_grad) == 324290


def test_c1_starts_from_mother_state_bitwise(spec, norm):
    full_state, base_state = M.c1_reference_state_full(spec, norm)
    a = M.build_model(spec, norm, "c1")
    b = M.build_model(spec, norm, "s_select")
    M.load_init_state(a, base_state, "c1")
    M.load_init_state(b, base_state, "s_select")
    sa, sb = a.state_dict(), b.state_dict()
    shared = [k for k in sa if k in sb]
    assert shared, "no shared parameters"
    for k in shared:
        assert torch.equal(sa[k], sb[k]), k
    #: WIDE_LOCAL must start from the *same* step-0 function: the surgery keeps
    #: the original rows/columns and zeroes the new ones.
    wide = M.build_model(spec, norm, "wide_local")
    M.load_init_state(wide, base_state, "wide_local")
    sw = wide.state_dict()
    assert torch.equal(sw["local.mlp.lins.0.weight"][:192], sa["local.mlp.lins.0.weight"])
    assert torch.equal(sw["local.mlp.lins.0.bias"][:192], sa["local.mlp.lins.0.bias"])
    assert float(sw["local.mlp.lins.0.bias"][192:].abs().sum()) == 0.0
    assert float(sw["local.mlp.lins.1.weight"][:, 192:].abs().sum()) == 0.0
    assert torch.equal(sw["local.mlp.lins.1.weight"][:, :192], sa["local.mlp.lins.1.weight"])


def test_alpha_endpoints_reproduce_full_and_marginal(spec, norm):
    """S-family contraction: coefficient 1 == FULL, coefficient 0 == frozen B5."""
    cache = D.load_cache("Lipophilicity", "valid")
    rows = list(range(6))
    batch = D.collate(cache, rows, path_count=np.ones(len(cache["path_cat"]), dtype=np.float32))
    assert batch["path_key_count"].min() == 1.0
    full = M.build_model(spec, norm, "c1")
    M.load_init_state(full, M.c1_reference_state(spec, norm), "c1")
    full.eval()
    shrink = M.build_model(spec, norm, "s_select").eval()
    M.load_init_state(shrink, M.c1_reference_state(spec, norm), "s_select")
    shrink.local.shrink_kappa.fill_(1.0)
    with torch.no_grad():
        y_full = full(batch)
        shrink.local.shrink_kind = "force_full"
        y_alpha1 = shrink(batch)
        shrink.local.shrink_kind = "force_zero"
        y_alpha0 = shrink(batch)
        shrink.local.shrink_kind = "select"
        shrink.local.shrink_kappa.fill_(1e9)    # a_r -> 0  => the marginal operator
        y_zero = shrink(batch)
    assert torch.allclose(y_alpha1, y_full, atol=1e-6), (y_alpha1 - y_full).abs().max()
    assert torch.allclose(y_alpha0, y_zero, atol=1e-6)
    assert not torch.allclose(y_alpha1, y_alpha0, atol=1e-4), "contraction is a no-op"


def test_permutation_table_is_frozen_and_shared():
    epochs = C.BASE_RECIPE["epochs"]
    p1 = D.load_perms("Lipophilicity", epochs)
    p2 = D.load_perms("Lipophilicity", epochs)
    assert np.array_equal(p1, p2)
    n = int(D.dataset_meta("Lipophilicity")["sizes"][0])
    assert p1.shape == (epochs, n)
    assert np.array_equal(np.sort(p1[0]), np.arange(n))
    #: every arm of a dataset shares one table, keyed only by (dataset, seed,
    #: epoch) and generated by one frozen generator
    assert C.SHUFFLE_SEED == 917000
