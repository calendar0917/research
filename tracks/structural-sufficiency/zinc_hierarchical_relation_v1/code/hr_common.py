def load_p3b_valid() -> dict[str, Any]:
    if not P3B_PATH.exists():
        raise SystemExit(f"missing frozen P3B valid predictions: {P3B_PATH}")
    got = sha256_file(P3B_PATH)
    if got != P3B_SHA256:
        raise SystemExit(f"P3B prediction hash mismatch: {got} != {P3B_SHA256}")
    z = np.load(P3B_PATH, allow_pickle=False)
    rows = z["row"].astype(np.int64)
    pred = z["pred"].astype(np.float64)
    if len(rows) != N_VALID or not np.array_equal(rows, np.arange(N_VALID)):
        raise SystemExit("frozen P3B valid rows are not 0..999")
    return {"row": rows, "pred": pred, "sha256": got}


def load_valid_groups() -> dict[str, np.ndarray]:
    """Fixed valid groups copied from the frozen generalization audit CSV."""
    import csv

    if not AUDIT_PER_MOLECULE.exists():
        raise SystemExit(f"missing audit table: {AUDIT_PER_MOLECULE}")
    rows: list[dict[str, str]] = []
    with open(AUDIT_PER_MOLECULE, newline="") as fh:
        for rec in csv.DictReader(fh):
            rows.append(rec)
    if len(rows) != N_VALID:
        raise SystemExit(f"audit table has {len(rows)} rows, expected {N_VALID}")
    rows.sort(key=lambda r: int(r["row_id"]))
    y = np.asarray([float(r["y_raw"]) for r in rows], dtype=np.float64)
    p3b_pred = np.asarray([float(r["pred_P3B_s0"]) for r in rows], dtype=np.float64)
    p3b_ae = np.asarray([float(r["abs_error_P3B_s0"]) for r in rows], dtype=np.float64)
    r2_unseen = np.asarray([float(r["r2_unseen_atom_frac"]) > 0.0 for r in rows], dtype=bool)
    r2_frac = np.asarray([float(r["r2_unseen_atom_frac"]) for r in rows], dtype=np.float64)
    ring_count = np.asarray([int(r["n_rings"]) for r in rows], dtype=np.int64)
    n_atoms = np.asarray([int(r["n_atoms"]) for r in rows], dtype=np.int64)
    cycle_rank = np.asarray([int(r["cycle_rank"]) for r in rows], dtype=np.int64)
    top10 = np.argsort(-p3b_ae, kind="stable")[:10]
    return {
        "y": y,
        "p3b_pred": p3b_pred,
        "p3b_ae": p3b_ae,
        "radius2_unseen": r2_unseen,
        "radius2_unseen_frac": r2_frac,
        "ring_count": ring_count,
        "n_atoms": n_atoms,
        "cycle_rank": cycle_rank,
        "p3b_top10": top10,
        "tail": y <= GATE["tail_threshold"],
        "ring_rich": ring_count >= GATE["ring_count_min"],
        "p3b_worst100": np.argsort(-p3b_ae, kind="stable")[:100],
    }


def group_table(
    ae_candidate: np.ndarray,
    ae_reference: np.ndarray,
    groups: Mapping[str, np.ndarray],
) -> dict[str, Any]:
    out: dict[str, Any] = {}
    for name, mask in groups.items():
        mask = np.asarray(mask, dtype=bool)
        if mask.sum() == 0:
            continue
        out[name] = {
            "n": int(mask.sum()),
            "candidate_mae": float(ae_candidate[mask].mean()),
            "reference_mae": float(ae_reference[mask].mean()),
            "delta_reference_minus_candidate": float(ae_reference[mask].mean() - ae_candidate[mask].mean()),
        }
    return out
