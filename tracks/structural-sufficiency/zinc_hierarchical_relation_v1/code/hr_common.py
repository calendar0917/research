def sha256_file(path: Path | str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def sha256_array(arr: np.ndarray, dtype: str = "float32") -> str:
    a = np.ascontiguousarray(np.asarray(arr, dtype=dtype))
    return hashlib.sha256(a.tobytes()).hexdigest()


def sha256_state_dict(state: Mapping[str, Any]) -> str:
    import torch

    h = hashlib.sha256()
    for key in sorted(state):
        value = state[key]
        if torch.is_tensor(value):
            arr = value.detach().cpu().contiguous()
            h.update(key.encode())
            h.update(str(tuple(arr.shape)).encode())
            h.update(arr.numpy().tobytes())
    return h.hexdigest()


def read_json(path: Path | str) -> Any:
    with open(path) as fh:
        return json.load(fh)


def write_json(path: Path | str, payload: Mapping[str, Any]) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as fh:
        json.dump(payload, fh, indent=2, sort_keys=False)
        fh.write("\n")


def write_once_json(path: Path | str, payload: Mapping[str, Any]) -> None:
    path = Path(path)
    if path.exists():
        raise SystemExit(f"refusing to overwrite {path}")
    write_json(path, payload)


